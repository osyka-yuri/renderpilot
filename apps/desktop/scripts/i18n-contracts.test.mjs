test('English contract parser rejects malformed tagged messages', () => {
  assert.throws(
    () =>
      parseEnglishContract(`
        const en = defineSourceCatalog({
          invalid: plural('count', { one: '{count} item' }),
        });
      `),
    /plural branches must be exactly one and other/,
  );
  assert.throws(
    () =>
      parseEnglishContract(`
        const en = defineSourceCatalog({
          invalid: select('tone', { other: 'Default' }),
        });
      `),
    /select branches must include other and at least one named case/,
  );
  assert.throws(
    () =>
      parseEnglishContract(`
        const en = defineSourceCatalog({
          invalid: '{valid} then {bad-name}',
        });
      `),
    /contains invalid placeholder syntax/,
  );
});

test('generator diagnostics identify the source file and message key', () => {
  assert.throws(
    () =>
      parseEnglishContract(`
        const en = defineSourceCatalog({
          'broken.message': '{valid} then {bad-name}',
        });
      `),
    /ui\/src\/shared\/i18n\/messages\/en\.ts: English message broken\.message contains invalid placeholder syntax/,
  );
});

test('source parsers reject malformed TypeScript and JSON with actionable diagnostics', () => {
  assert.throws(
    () => parseEnglishContract('const en = defineSourceCatalog({ broken: "value"; });'),
    /ui\/src\/shared\/i18n\/messages\/en\.ts: TypeScript syntax error at 1:\d+:/,
  );
  assert.throws(() => parseJsonSource('{"broken":'), /invalid JSON/);
});

test('desktop command-error manifest validates codes, references, and strict shapes', () => {
  const english = parseEnglishContract(`
    const en = defineSourceCatalog({
      'error.message': 'Failed.',
      'error.action': 'Try again.',
      'warning.count': plural('count', { one: 'One', other: '{count} items' }),
    });
  `);
  const valid = {
    schemaVersion: 1,
    commandErrors: [
      {
        code: 'operation_failed',
        rustVariant: 'OperationFailed',
        messageKey: 'error.message',
        severity: 'error',
        actions: ['retry'],
      },
    ],
    suggestedActions: [{ code: 'retry', messageKey: 'error.action' }],
  };

  assert.equal(parseDesktopCommandErrorContract(valid, english).schemaVersion, 1);
  assert.throws(
    () => parseDesktopCommandErrorContract({ ...valid, schemaVersion: 2 }, english),
    /unsupported schemaVersion/,
  );
  assert.throws(
    () =>
      parseDesktopCommandErrorContract(
        { ...valid, commandErrors: [...valid.commandErrors, valid.commandErrors[0]] },
        english,
      ),
    /duplicate code/,
  );
  assert.throws(
    () =>
      parseDesktopCommandErrorContract(
        {
          ...valid,
          commandErrors: [{ ...valid.commandErrors[0], code: `a${'b'.repeat(64)}` }],
        },
        english,
      ),
    /invalid machine code/,
  );
  assert.throws(
    () =>
      parseDesktopCommandErrorContract(
        {
          ...valid,
          commandErrors: [{ ...valid.commandErrors[0], rustVariant: 'invalid_variant' }],
        },
        english,
      ),
    /invalid rustVariant/,
  );
  assert.throws(
    () =>
      parseDesktopCommandErrorContract(
        {
          ...valid,
          commandErrors: [{ ...valid.commandErrors[0], messageKey: 'error.missing' }],
        },
        english,
      ),
    /missing English message/,
  );
  assert.throws(
    () =>
      parseDesktopCommandErrorContract(
        {
          ...valid,
          suggestedActions: [{ ...valid.suggestedActions[0], messageKey: 'error.missing' }],
        },
        english,
      ),
    /missing English message/,
  );
  assert.throws(
    () =>
      parseDesktopCommandErrorContract(
        {
          ...valid,
          commandErrors: [{ ...valid.commandErrors[0], actions: ['missing'] }],
        },
        english,
      ),
    /unknown suggested action/,
  );
  assert.throws(
    () => parseDesktopCommandErrorContract({ ...valid, unexpected: true }, english),
    /unknown field/,
  );
  assert.throws(
    () =>
      parseDesktopCommandErrorContract(
        {
          ...valid,
          commandErrors: [{ ...valid.commandErrors[0], recoveryBundlePath: false }],
        },
        english,
      ),
    /must be true when present/,
  );
  assert.throws(
    () =>
      parseDesktopCommandErrorContract(
        {
          ...valid,
          commandErrors: [
            { ...valid.commandErrors[0], severity: 'warning', recoveryBundlePath: true },
          ],
        },
        english,
      ),
    /exposes a recovery path but is not an error/,
  );
});

