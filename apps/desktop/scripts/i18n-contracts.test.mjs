test('generated source formatting honors file-specific oxfmt overrides', async () => {
  const directory = await mkdtemp(path.join(tmpdir(), 'renderpilot-i18n-contracts-'));
  const configPath = path.join(directory, '.oxfmtrc.json');
  const filePath = path.join(directory, 'generated', 'contract.ts');

  try {
    await mkdir(path.dirname(filePath), { recursive: true });
    await writeFile(
      configPath,
      JSON.stringify({
        singleQuote: false,
        overrides: [{ files: ['generated/**/*.ts'], options: { singleQuote: true } }],
      }),
      'utf8',
    );

    assert.equal(
      await formatGeneratedSource(filePath, 'const contract = "value";\n', configPath),
      "const contract = 'value';\n",
    );
  } finally {
    await rm(directory, { recursive: true, force: true });
  }
});

