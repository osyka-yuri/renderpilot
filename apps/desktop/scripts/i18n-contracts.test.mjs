test('stale detection reports missing and mismatched generated outputs', async () => {
  const directory = await mkdtemp(path.join(tmpdir(), 'renderpilot-i18n-stale-'));
  const missingPath = path.join(directory, 'missing.ts');
  const mismatchedPath = path.join(directory, 'mismatched.ts');

  try {
    await writeFile(mismatchedPath, 'actual\n', 'utf8');
    const stale = await checkI18nContractOutputs(
      new Map([
        [missingPath, 'expected\n'],
        [mismatchedPath, 'expected\n'],
      ]),
    );

    assert.equal(stale.length, 2);
    assert.equal(stale[0].endsWith('missing.ts'), true);
    assert.equal(stale[1].endsWith('mismatched.ts'), true);
  } finally {
    await rm(directory, { recursive: true, force: true });
  }
});

